app.post("/api/settings", asyncRoute(async (req, res) => {
  const b = req.body || {};
  const settingsData = {
    shop_name: (b.shop_name || "DIGI DIGITAL SERVICE").trim(),
    pan_number: (b.pan_number || "").trim(),
    mobile_number: (b.mobile_number || "").trim(),
    address: (b.address || "").trim(),
    tagline: (b.tagline || "Digital & Online Service Center").trim(),
    footer_note: (b.footer_note || "Thank you for your visit!").trim(),
    default_format: b.default_format === "a4" ? "a4" : "thermal",
    logo_url: b.logo_url || ""
  };
  await query(
    `INSERT INTO settings (key, value, updated_at)
     VALUES ('shop_profile', $1, NOW())
     ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW()`,
    [JSON.stringify(settingsData)]
  );
  res.json(settingsData);
}));

app.get("/api/reports/summary", asyncRoute(async (req, res) => {
  const { from, to } = req.query;
  const start = from || new Date().toISOString().slice(0,10);
  const end = to || start;
  const sales = await query(`
    SELECT COUNT(*)::int AS transaction_count,
      COALESCE(SUM(total),0)::numeric(12,2) AS total_sales,
      COALESCE(SUM(CASE WHEN payment_method='Cash' THEN total ELSE 0 END),0)::numeric(12,2) AS cash_total,
      COALESCE(SUM(CASE WHEN payment_method<>'Cash' THEN total ELSE 0 END),0)::numeric(12,2) AS online_total
    FROM transactions WHERE transaction_date >= $1::date AND transaction_date < ($2::date + INTERVAL '1 day')
  `, [start, end]);
  const expenses = await query(`
    SELECT COALESCE(SUM(amount),0)::numeric(12,2) AS total_expenses
    FROM expenses WHERE expense_date >= $1::date AND expense_date <= $2::date
  `, [start, end]);
  const s = sales.rows[0], e = expenses.rows[0];
  res.json({ ...s, total_expenses: e.total_expenses, net_after_expenses: Number(s.total_sales) - Number(e.total_expenses), from: start, to: end });
}));

