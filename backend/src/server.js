app.post("/api/expenses", [
  body("title").trim().isLength({ min: 1, max: 150 }).withMessage("Expense title is required."),
  body("amount").isFloat({ gt: 0 }).withMessage("Expense amount must be greater than zero.")
], validate, asyncRoute(async (req, res) => {
  const b = req.body;
  const result = await query(
    "INSERT INTO expenses (title,category,amount,note,expense_date) VALUES ($1,$2,$3,$4,COALESCE($5::date,CURRENT_DATE)) RETURNING *",
    [b.title.trim(), (b.category || "Other").trim(), Number(b.amount), (b.note || "").trim() || null, b.expense_date || null]
  );
  res.status(201).json(result.rows[0]);
}));

app.patch("/api/transactions/:id/payment", [
  body("payment_status").isIn(["Paid", "Pending"]).withMessage("Payment status must be Paid or Pending."),
  body("payment_method").optional().isIn(["Cash", "eSewa", "Khalti", "Bank", "Other"]).withMessage("Invalid payment method.")
], validate, asyncRoute(async (req, res) => {
  if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: "Invalid transaction ID." });
  const { payment_status, payment_method } = req.body;
  const updates = ["payment_status = $1"];
  const params = [payment_status];
  if (payment_method) {
    params.push(payment_method);
    updates.push(`payment_method = $${params.length}`);
  }
  params.push(req.params.id);
  const result = await query(
    `UPDATE transactions SET ${updates.join(", ")} WHERE id = $${params.length} RETURNING *`,
    params
  );
  if (!result.rows.length) return res.status(404).json({ error: "Transaction not found." });
  res.json(result.rows[0]);
}));

app.delete("/api/transactions/:id", asyncRoute(async (req, res) => {
  if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: "Invalid transaction ID." });
  await query("DELETE FROM transactions WHERE id=$1", [req.params.id]);
  res.status(204).end();
}));

